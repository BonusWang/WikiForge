CREATE TABLE system_dictionaries (
    id BIGINT NOT NULL AUTO_INCREMENT,
    dict_type VARCHAR(64) NOT NULL,
    dict_code VARCHAR(128) NOT NULL,
    label_zh VARCHAR(128) NOT NULL,
    description_zh VARCHAR(512) NULL,
    sort_order INT NOT NULL DEFAULT 0,
    color_token VARCHAR(64) NOT NULL DEFAULT 'neutral',
    is_terminal TINYINT(1) NOT NULL DEFAULT 0,
    is_success TINYINT(1) NOT NULL DEFAULT 0,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_system_dictionaries_type_code (dict_type, dict_code),
    KEY idx_system_dictionaries_type_sort_active (dict_type, is_active, sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

