CREATE TABLE wiki_ingest_runs (
    id BIGINT NOT NULL AUTO_INCREMENT,
    run_uid VARCHAR(64) NOT NULL,
    source_file_id BIGINT NOT NULL,
    file_uid VARCHAR(64) NOT NULL,
    file_name VARCHAR(512) NULL,
    status_code VARCHAR(128) NOT NULL DEFAULT '已创建',
    status_label VARCHAR(128) NOT NULL DEFAULT '已创建',
    source_page_path VARCHAR(1024) NULL,
    index_updated TINYINT(1) NOT NULL DEFAULT 0,
    log_entry_appended TINYINT(1) NOT NULL DEFAULT 0,
    write_status_code VARCHAR(128) NOT NULL DEFAULT '已创建',
    write_status_label VARCHAR(128) NOT NULL DEFAULT '已创建',
    failure_reason TEXT NULL,
    managed_block_preview TEXT NULL,
    log_entry_preview TEXT NULL,
    obsidian_uri VARCHAR(2048) NULL,
    retryable TINYINT(1) NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at DATETIME NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_wiki_ingest_runs_run_uid (run_uid),
    KEY idx_wiki_ingest_runs_file (source_file_id),
    KEY idx_wiki_ingest_runs_file_uid_created (file_uid, created_at),
    KEY idx_wiki_ingest_runs_status_created (status_code, created_at),
    CONSTRAINT fk_wiki_ingest_runs_source_file FOREIGN KEY (source_file_id) REFERENCES source_files(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
